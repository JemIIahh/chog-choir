import { chromium } from 'playwright'
import assert from 'node:assert/strict'

const HOLDER = '0x3d38fee3e1a4c43d8fcf715aa6c9ff025074e7e0' // owner of token 1 on Monad mainnet (public data)
const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] })
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } })
await ctx.addInitScript(acct => {
  const provider = { request: async ({ method }) => (method === 'eth_requestAccounts' || method === 'eth_accounts' ? [acct] : method === 'eth_chainId' ? '0x8f' : null), on() {}, removeListener() {} }
  const info = { uuid: 'mock', name: 'Mock wallet', icon: 'data:image/svg+xml;base64,PHN2Zy8+', rdns: 'test.mock' }
  window.addEventListener('eip6963:requestProvider', () => window.dispatchEvent(new CustomEvent('eip6963:announceProvider', { detail: { info, provider } })))
}, HOLDER)
const p = await ctx.newPage()
const errors = []
p.on('pageerror', e => errors.push(e.message))
p.on('console', m => { if (m.type() === 'error' && !/429|Failed to load resource/.test(m.text())) errors.push(m.text()) })
const step = m => console.log('•', m)

await p.goto('http://127.0.0.1:5188/', { waitUntil: 'networkidle' })
await p.waitForSelector('.onb')
step('first visit shows the welcome')
await p.screenshot({ path: '/tmp/onb-1.png' })

await p.click('button:has-text("Hear a Chog sing")')
await p.waitForSelector('.onb .play.on', { timeout: 5000 })
await p.waitForTimeout(1200)
assert.ok(await p.evaluate(() => document.querySelector('.onb .bubble, .onb .sleeve') !== null))
step('step 1: the Chog plays; the play button becomes pause')
await p.screenshot({ path: '/tmp/onb-1b.png' })

await p.click('.onb-nav button:has-text("Next")')
await p.waitForSelector('text=The mouth picks the vowel.')
assert.equal(await p.evaluate(() => window.__choir ? 1 : 1), 1)
await p.click('.vbtn.v4'); await p.waitForTimeout(300)
await p.click('.chip:has-text("soprano")'); await p.waitForTimeout(300)
assert.equal(await p.locator('.vbtn.on').count(), 1)
step('step 2: vowels and registers are tappable')
await p.screenshot({ path: '/tmp/onb-2.png' })

await p.click('.onb-nav button:has-text("Next")')
await p.waitForSelector('text=Now find yours.')
await p.fill('.onb .finder-in input', '1462'); await p.click('.onb button:has-text("Hear its song")')
await p.waitForSelector('.onb .play, .onb .sleeve')
assert.match(await p.textContent('.onb-cap'), /Chog #1462/)
step('step 3: typing a number loads that Chog')
await p.fill('.onb .finder-in input', '99999'); await p.click('.onb button:has-text("Hear its song")')
await p.waitForSelector('.onb .w-err')
step('step 3: a bad number explains itself')
await p.click('.onb button:has-text("Connect Mock wallet")')
await p.waitForSelector('.onb .holder .thumb', { timeout: 30000 })
const held = await p.locator('.onb .holder .thumb').count()
assert.ok(held >= 1)
step(`step 3: wallet lookup found ${held} real Chog(s) for the holder, read-only`)
await p.screenshot({ path: '/tmp/onb-3.png' })

await p.click('.onb-nav button:has-text("Next")')
await p.waitForSelector('text=Then sing together.')
await p.waitForSelector('.onb .loft canvas')
step('step 4: the loft is shown')
await p.screenshot({ path: '/tmp/onb-4.png' })
await p.click('.onb button:has-text("Open the Choir")')
await p.waitForSelector('.onb', { state: 'detached' })
assert.equal(await p.evaluate(() => location.hash), '#choir')
step('finishing lands in the Choir')

await p.goto('http://127.0.0.1:5188/', { waitUntil: 'networkidle' })
assert.equal(await p.locator('.onb').count(), 0)
step('second visit: no welcome')
await p.click('.how'); await p.waitForSelector('.onb')
await p.keyboard.press('Escape'); await p.waitForSelector('.onb', { state: 'detached' })
step('"How it works" reopens it, Escape closes it')

const ctx2 = await b.newContext({ viewport: { width: 1440, height: 900 } }); const p2 = await ctx2.newPage()
await p2.goto('http://127.0.0.1:5188/#c=1462', { waitUntil: 'networkidle' }); await p2.waitForSelector('.hero')
assert.equal(await p2.locator('.onb').count(), 0)
step('a shared link to a song skips the welcome')

const ctx3 = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 }); const p3 = await ctx3.newPage()
await p3.goto('http://127.0.0.1:5188/', { waitUntil: 'networkidle' }); await p3.waitForSelector('.onb')
await p3.screenshot({ path: '/tmp/onb-mobile.png' })
await p3.click('.onb-nav button:has-text("Next")'); await p3.click('.onb-nav button:has-text("Next")')
await p3.screenshot({ path: '/tmp/onb-mobile-3.png' })
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no page errors')
await b.close()
assert.equal(errors.length, 0)
console.log('ONBOARDING PASSED')
